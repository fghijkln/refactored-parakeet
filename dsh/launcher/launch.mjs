#!/usr/bin/env node
/**
 * Parakeet's DSH entry point. Same CLI as `dsh` (argv is forwarded verbatim),
 * plus the one thing a packaged app must supply: the bundled pnpm, invoked
 * through this very node binary, so `dsh plugin add` and the web Plugins page
 * work on Android where there is no `pnpm` on PATH (and nothing in the app's
 * data directory may be exec'd directly).
 *
 *   node launch.mjs web --no-open --host 127.0.0.1 --port 0 --patch parakeet.patch.yml
 *   node launch.mjs headless "task"
 *   node launch.mjs plugin --profile web add <npm-package>
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const nodeModules = join(here, 'node_modules');

// Prefer the bundled pnpm; fall back to a PATH pnpm (desktop/CI use).
const pnpmEntry = ['pnpm/bin/pnpm.mjs', 'pnpm/bin/pnpm.cjs']
  .map((p) => join(nodeModules, p))
  .find((p) => existsSync(p));

const env = {};
for (const key of ['PATH', 'HOME', 'TMPDIR', 'LD_LIBRARY_PATH', 'SSL_CERT_DIR', 'SSL_CERT_FILE', 'npm_config_registry']) {
  if (process.env[key] !== undefined) env[key] = process.env[key];
}
// pnpm keeps its store under $HOME by default; on Android that is the app's
// private files dir, which the app sets as HOME.
const packageManager = pnpmEntry === undefined ? undefined : { command: process.execPath, args: [pnpmEntry], env };

if (process.argv.includes('--parakeet-selftest')) {
  // Cheap health probe the app and CI run before booting DSH proper.
  const { version } = await import(join(nodeModules, '@deepseek-ai/dsh/package.json'), { with: { type: 'json' } }).then((m) => m.default);
  console.log(JSON.stringify({ node: process.version, platform: process.platform, arch: process.arch, dsh: version, pnpm: pnpmEntry ?? null }));
  process.exit(0);
}

// App-managed overlay: provider route, Android sandbox policy, root tool.
if (process.env.PARAKEET_CONFIG && existsSync(process.env.PARAKEET_CONFIG)) {
  const { buildPatch, withPatchArg } = await import('./parakeet-config.mjs');
  const cfg = JSON.parse(readFileSync(process.env.PARAKEET_CONFIG, 'utf8'));
  if (cfg?.provider?.kind === 'deepseek' && process.env.PARAKEET_API_KEY && !process.env.DEEPSEEK_API_KEY) {
    process.env.DEEPSEEK_API_KEY = process.env.PARAKEET_API_KEY;
  }
  const home = process.env.DSH_HOME ?? join(process.env.HOME ?? here, '.dsh');
  mkdirSync(home, { recursive: true });
  const patchFile = join(home, 'parakeet.patch.yml');
  writeFileSync(patchFile, `# generated by Parakeet on every launch; edit settings in the app\n${JSON.stringify(buildPatch(cfg), null, 2)}\n`);
  const rest = withPatchArg(process.argv.slice(2), patchFile);
  process.argv.splice(2, process.argv.length - 2, ...rest);
}

const { runCli } = await import(join(nodeModules, '@deepseek-ai/dsh/lib/bin.js'));
await runCli(packageManager === undefined ? {} : { packageManager });
